import assert from 'node:assert/strict';
import { build } from 'esbuild';
import path from 'node:path';
import Module from 'node:module';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({entryPoints:[path.join(root,'src/app/utils/operational-horometer.ts')], alias:{'@':path.join(root,'src')},bundle:true,platform:'node',format:'cjs',write:false});
const module = new Module(path.join(root,'scripts/clock-fixture.cjs'));
module._compile(result.outputFiles[0].text,module.id);
const { operationalClock, operationalHours } = module.exports;
const since='2026-10-04T10:00:00';
const before=Date.parse('2026-10-04T15:59:59Z');
const hour=Date.parse('2026-10-04T16:00:00Z');
assert.equal(operationalClock(1000,'FUNCIONAMIENTO',since,before),'1000:59:59');
assert.equal(operationalClock(1000,'FUNCIONAMIENTO',since,hour),'1001:00:00');
assert.equal(operationalHours(1000,'FUNCIONAMIENTO',since,hour),1001);
assert.equal(operationalClock(1000.5,'PARADO',since,hour),'1000:30:00');
assert.equal(operationalClock(1000.5,'PARADO',since,hour+86400000),'1000:30:00');
assert.equal(operationalClock(1000.5,'FUNCIONAMIENTO',null,hour),'1000:30:00');
assert.equal(operationalClock(1000,'FUNCIONAMIENTO',since,Date.parse('2026-10-04T14:00:00Z')),'1000:00:00');
console.log('PASS: contador automático por segundo, límite exacto de una hora, equipo parado y zona horaria de Ecuador');
